/* =========================================================
   SEARCH SUGGESTIONS
========================================================= */

function showSearchSuggestions(query) {

    const searchTerm =
        query.trim().toLowerCase();


    if (!searchTerm) {

        searchSuggestions.classList.remove(
            "active"
        );

        searchSuggestions.innerHTML =
            "";

        return;

    }


    const matches =
        products
            .filter(product =>

                product.name
                    .toLowerCase()
                    .includes(searchTerm)

                ||

                product.category
                    .toLowerCase()
                    .includes(searchTerm)

            )
            .slice(0, 6);


    if (matches.length === 0) {

        searchSuggestions.classList.remove(
            "active"
        );

        searchSuggestions.innerHTML =
            "";

        return;

    }


    searchSuggestions.innerHTML =
        "";


    matches.forEach(product => {

        const item =
            document.createElement("div");

        item.className =
            "suggestion-item";


        item.innerHTML = `

            <img
                src="${product.image}"
                alt="${product.name}"
            >

            <div class="suggestion-info">

                <span class="suggestion-name">
                    ${product.name}
                </span>

                <span class="suggestion-meta">
                    ${product.category}
                    ·
                    ${product.size}
                    ·
                    ₹${product.price}
                </span>

            </div>

        `;


        const suggestionImage =
            item.querySelector("img");


        imageFallback(
            suggestionImage
        );


        item.addEventListener(
            "click",
            () => {

                window.location.href =
                    `/product/${product.id}`;

            }
        );


        searchSuggestions.appendChild(
            item
        );

    });


    searchSuggestions.classList.add(
        "active"
    );

}


searchInput.addEventListener(
    "input",
    event => {

        showSearchSuggestions(
            event.target.value
        );

    }
);


/* =========================================================
   SEARCH
========================================================= */

function performSearch() {

    const query =
        searchInput.value.trim();


    if (!query) {
        return;
    }


    window.location.href =
        `/search?q=${encodeURIComponent(
            query
        )}`;

}


searchButton.addEventListener(
    "click",
    performSearch
);


searchInput.addEventListener(
    "keydown",
    event => {

        if (
            event.key === "Enter"
        ) {

            event.preventDefault();

            performSearch();

        }

    }
);


/* =========================================================
   CLOSE SEARCH SUGGESTIONS
========================================================= */

document.addEventListener(
    "click",
    event => {

        if (
            !event.target.closest(
                ".header-search"
            )
        ) {

            searchSuggestions.classList.remove(
                "active"
            );

        }

    }
);


