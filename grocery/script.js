/* =========================================================
   DISCOUNT
========================================================= */

function getDiscount(product) {

    if (
        !product.mrp ||
        product.mrp <= product.price
    ) {
        return 0;
    }

    return Math.round(
        (
            (product.mrp - product.price)
            /
            product.mrp
        ) * 100
    );

}


/* =========================================================
   CART
========================================================= */

function getCart() {

    try {

        const cart =
            localStorage.getItem("marteyCart");

        if (!cart) {
            return [];
        }

        const parsed =
            JSON.parse(cart);

        return Array.isArray(parsed)
            ? parsed
            : [];

    } catch (error) {

        return [];

    }

}


function saveCart(cart) {

    localStorage.setItem(
        "marteyCart",
        JSON.stringify(cart)
    );

}


function getCartQuantity(productId) {

    const cart = getCart();

    const item = cart.find(
        item =>
            Number(
                item.id ??
                item.productId ??
                item.productID
            ) === Number(productId)
    );

    if (!item) {
        return 0;
    }

    return Number(
        item.quantity ??
        item.qty ??
        1
    );

}


function updateCartCount() {

    const cart = getCart();

    let total = 0;

    cart.forEach(item => {

        total += Number(
            item.quantity ??
            item.qty ??
            1
        );

    });

    cartCount.textContent = total;

}


function addToCart(productId) {

    const cart = getCart();

    const existingItem = cart.find(
        item =>
            Number(
                item.id ??
                item.productId ??
                item.productID
            ) === Number(productId)
    );


    if (existingItem) {

        if (
            existingItem.quantity !== undefined
        ) {

            existingItem.quantity += 1;

        } else if (
            existingItem.qty !== undefined
        ) {

            existingItem.qty += 1;

        } else {

            existingItem.quantity = 2;

        }

    } else {

        cart.push({
            id: productId,
            quantity: 1
        });

    }


    saveCart(cart);

    updateCartCount();

    renderProducts();

}


/* =========================================================
   FILTERS
========================================================= */

function getSelectedFilters() {

    const categoryFilters = [
        ...document.querySelectorAll(
            'input[data-filter="category"]:checked'
        )
    ].map(
        input => input.value
    );


    const priceFilters = [
        ...document.querySelectorAll(
            'input[data-filter="price"]:checked'
        )
    ].map(
        input => input.value
    );


    return {
        categories: categoryFilters,
        prices: priceFilters
    };

}


function applyFilters() {

    const filters =
        getSelectedFilters();

    let filteredProducts =
        [...products];


    /* CATEGORY */

    if (
        filters.categories.length > 0
    ) {

        filteredProducts =
            filteredProducts.filter(
                product =>
                    filters.categories.includes(
                        product.category
                    )
            );

    }


    /* PRICE */

    if (
        filters.prices.length > 0
    ) {

        filteredProducts =
            filteredProducts.filter(
                product => {

                    return filters.prices.some(
                        priceFilter => {

                            if (
                                priceFilter ===
                                "under100"
                            ) {

                                return (
                                    product.price <
                                    100
                                );

                            }


                            if (
                                priceFilter ===
                                "100to250"
                            ) {

                                return (
                                    product.price >= 100 &&
                                    product.price <= 250
                                );

                            }


                            if (
                                priceFilter ===
                                "above250"
                            ) {

                                return (
                                    product.price >
                                    250
                                );

                            }


                            return true;

                        }
                    );

                }
            );

    }


    return filteredProducts;

}


/* =========================================================
   SORT
========================================================= */

function sortProducts(productList) {

    const sortValue =
        sortSelect.value;

    const sorted =
        [...productList];


    if (
        sortValue === "price-low"
    ) {

        sorted.sort(
            (a, b) =>
                a.price - b.price
        );

    }


    else if (
        sortValue === "price-high"
    ) {

        sorted.sort(
            (a, b) =>
                b.price - a.price
        );

    }


    else if (
        sortValue === "discount"
    ) {

        sorted.sort(
            (a, b) =>
                getDiscount(b) -
                getDiscount(a)
        );

    }


    return sorted;

}


