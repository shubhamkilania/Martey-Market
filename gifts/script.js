/* =========================
   IMAGE
========================= */

function getImage(product) {

    return `../assets/products/${product.image}`;

}


/* =========================
   DISCOUNT
========================= */

function getDiscount(product) {

    if (
        !product.mrp ||
        product.mrp <= product.price
    ) {
        return 0;
    }

    return Math.round(
        (
            (product.mrp - product.price) /
            product.mrp
        ) * 100
    );

}


/* =========================
   CART
========================= */

function getCart() {

    try {

        const keys = [
            "marteyCart",
            "cart",
            "MARTEY_CART"
        ];

        for (const key of keys) {

            const saved =
                localStorage.getItem(key);

            if (!saved) {
                continue;
            }

            const parsed =
                JSON.parse(saved);

            if (Array.isArray(parsed)) {
                return parsed;
            }

            if (
                parsed &&
                Array.isArray(parsed.items)
            ) {
                return parsed.items;
            }

        }

    } catch (error) {

        console.error(
            "Cart read error:",
            error
        );

    }

    return [];

}


function normalizeCart(cart) {

    return cart.map(item => {

        if (typeof item === "number") {

            return {
                id: item,
                quantity: 1
            };

        }

        return {

            ...item,

            id: Number(
                item.id ??
                item.productId ??
                item.productID
            ),

            quantity: Number(
                item.quantity ??
                item.qty ??
                1
            )

        };

    });

}


function saveCart(cart) {

    localStorage.setItem(
        "marteyCart",
        JSON.stringify(cart)
    );

}


function updateCartCount() {

    const cart =
        normalizeCart(getCart());

    const total =
        cart.reduce(
            (sum, item) =>
                sum + (
                    Number(item.quantity) || 0
                ),
            0
        );

    cartCount.textContent = total;

}


function addToCart(productId) {

    let cart =
        normalizeCart(getCart());

    const existing =
        cart.find(
            item =>
                Number(item.id) ===
                Number(productId)
        );

    if (existing) {

        existing.quantity += 1;

    } else {

        cart.push({
            id: Number(productId),
            quantity: 1
        });

    }

    saveCart(cart);

    updateCartCount();

}


/* =========================
   FILTERS
========================= */

function getSelectedCategories() {

    return [
        ...document.querySelectorAll(
            ".category-filter:checked"
        )
    ].map(
        input => input.value
    );

}


function getSelectedPrices() {

    return [
        ...document.querySelectorAll(
            ".price-filter:checked"
        )
    ].map(
        input => input.value
    );

}


function priceMatches(
    product,
    filters
) {

    if (!filters.length) {
        return true;
    }

    return filters.some(filter => {

        if (filter === "under250") {

            return product.price < 250;

        }

        if (filter === "250-750") {

            return (
                product.price >= 250 &&
                product.price <= 750
            );

        }

        if (filter === "above750") {

            return product.price > 750;

        }

        return true;

    });

}


/* =========================
   SEARCH
========================= */

function getSearchQuery() {

    return searchInput.value
        .trim()
        .toLowerCase();

}


function searchMatches(
    product,
    query
) {

    if (!query) {
        return true;
    }

    const text = `
        ${product.name}
        ${product.category}
        ${product.size}
    `.toLowerCase();

    return text.includes(query);

}


function renderSearchSuggestions() {

    const query =
        searchInput.value
            .trim()
            .toLowerCase();

    searchSuggestions.innerHTML = "";

    if (!query) {

        searchSuggestions.classList.remove(
            "active"
        );

        return;

    }


    const matches =
        products
            .filter(product =>
                product.name
                    .toLowerCase()
                    .includes(query) ||

                product.category
                    .toLowerCase()
                    .includes(query)
            )
            .slice(0, 6);


    if (!matches.length) {

        searchSuggestions.classList.remove(
            "active"
        );

        return;

    }


    matches.forEach(product => {

        const item =
            document.createElement("div");

        item.className =
            "suggestion-item";

        item.innerHTML = `

            <img
                src="${getImage(product)}"
                alt="${product.name}"
                onerror="
                    this.src='../assets/products/martey-gift-card.jpg'
                "
            >

            <div class="suggestion-info">

                <strong>
                    ${product.name}
                </strong>

                <span>
                    ${product.category}
                    · ₹${product.price}
                </span>

            </div>
        `;


        item.addEventListener(
            "click",
            () => {

                window.location.href =
                    `/product/${product.id}`;

            }
        );


        searchSuggestions.appendChild(item);

    });


    searchSuggestions.classList.add(
        "active"
    );

}


/* =========================
   SORT
========================= */

function sortProducts(
    list,
    sortType
) {

    const sorted =
        [...list];

    if (sortType === "price-low") {

        sorted.sort(
            (a, b) =>
                a.price - b.price
        );

    }


    if (sortType === "price-high") {

        sorted.sort(
            (a, b) =>
                b.price - a.price
        );

    }


    if (sortType === "discount") {

        sorted.sort(
            (a, b) =>
                getDiscount(b) -
                getDiscount(a)
        );

    }


    return sorted;

}


/* =========================
   FILTERED PRODUCTS
========================= */

function getFilteredProducts() {

    const query =
        getSearchQuery();

    const selectedCategories =
        getSelectedCategories();

    const selectedPrices =
        getSelectedPrices();


    let filtered =
        products.filter(product => {

            const categoryMatch =
                selectedCategories.length === 0 ||
                selectedCategories.includes(
                    product.category
                );


            const priceMatch =
                priceMatches(
                    product,
                    selectedPrices
                );


            const searchMatch =
                searchMatches(
                    product,
                    query
                );


            return (
                categoryMatch &&
                priceMatch &&
                searchMatch
            );

        });


    filtered =
        sortProducts(
            filtered,
            sortSelect.value
        );


    return filtered;

}


/* =========================
   RENDER PRODUCTS
========================= */

function renderProducts() {

    const filtered =
        getFilteredProducts();


    productGrid.innerHTML = "";


    productCount.textContent =
        `${filtered.length} product${
            filtered.length !== 1
                ? "s"
                : ""
        } found`;


    if (!filtered.length) {

        emptyState.classList.add(
            "active"
        );

        return;

    }


    emptyState.classList.remove(
        "active"
    );


    filtered.forEach(product => {

        const discount =
            getDiscount(product);


        const card =
            document.createElement("article");


        card.className =
            "product-card";


        card.innerHTML = `

            <div
                class="product-image-wrap"
                data-product="${product.id}"
            >

                ${
                    discount > 0
                        ? `
                            <span class="discount-badge">
                                ${discount}% OFF
                            </span>
                          `
                        : ""
                }

                <img
                    src="${getImage(product)}"
                    alt="${product.name}"
                    loading="lazy"
                    onerror="
                        this.src='../assets/products/martey-gift-card.jpg'
                    "
                >

            </div>


            <div class="product-content">

                <div class="product-category">
                    ${product.category}
                </div>


                <div
                    class="product-name"
                    data-product="${product.id}"
                >
                    ${product.name}
                </div>


                <div class="product-size">
                    ${product.size}
                </div>


                <div class="rating">

                    <span class="rating-star">
                        ★
                    </span>

                    ${product.rating}

                </div>


                <div class="price-row">

                    <strong class="price">
                        ₹${product.price}
                    </strong>

                    ${
                        product.mrp !== product.price
                            ? `
                                <span class="mrp">
                                    ₹${product.mrp}
                                </span>
                              `
                            : ""
                    }

                </div>


                <div class="card-bottom">

                    <button
                        class="add-btn"
                        data-add="${product.id}"
                    >
                        Add to Cart
                    </button>

                </div>

            </div>
        `;


        productGrid.appendChild(card);

    });


    attachProductEvents();

}


/* =========================
   PRODUCT EVENTS
========================= */

function attachProductEvents() {

    document
        .querySelectorAll("[data-product]")
        .forEach(element => {

            element.addEventListener(
                "click",
                () => {

                    const id =
                        element.dataset.product;

                    window.location.href =
                        `/product/${id}`;

                }
            );

        });


    document
        .querySelectorAll("[data-add]")
        .forEach(button => {

            button.addEventListener(
                "click",
                event => {

                    event.stopPropagation();


                    const id =
                        Number(
                            button.dataset.add
                        );


                    addToCart(id);


                    button.textContent =
                        "Added ✓";


                    button.classList.add(
                        "added"
                    );


                    setTimeout(() => {

                        button.textContent =
                            "Add to Cart";

                        button.classList.remove(
                            "added"
                        );

                    }, 900);

                }
            );

        });

}


