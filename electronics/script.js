function updateAddButtons() {

    document
        .querySelectorAll(".add-button")
        .forEach(button => {

            const quantity =
                getCartQuantity(
                    button.dataset.id
                );

            button.textContent =
                quantity > 0
                    ? "Added ✓"
                    : "ADD";

            button.classList.toggle(
                "added",
                quantity > 0
            );

        });
}


/* =========================================================
   PRICE FILTER
========================================================= */

function matchesPrice(product) {

    if (!selectedPrices.length) {
        return true;
    }

    return selectedPrices.some(
        range => {

            if (range === "under250") {
                return product.price < 250;
            }

            if (range === "250to750") {
                return (
                    product.price >= 250 &&
                    product.price <= 750
                );
            }

            if (range === "above750") {
                return product.price > 750;
            }

            return true;
        }
    );
}


/* =========================================================
   APPLY FILTERS
========================================================= */

function applyFilters() {

    let filtered =
        [...products];


    if (selectedCategories.length) {

        filtered =
            filtered.filter(product =>
                selectedCategories.includes(
                    product.category
                )
            );
    }


    filtered =
        filtered.filter(matchesPrice);


    const sortValue =
        sortSelect.value;


    if (sortValue === "price-low") {

        filtered.sort(
            (a, b) =>
                a.price - b.price
        );
    }


    if (sortValue === "price-high") {

        filtered.sort(
            (a, b) =>
                b.price - a.price
        );
    }


    if (sortValue === "discount") {

        filtered.sort(
            (a, b) =>
                getDiscount(b) -
                getDiscount(a)
        );
    }


    renderProducts(filtered);

    renderActiveFilters();
}


/* =========================================================
   ACTIVE FILTERS
========================================================= */

function renderActiveFilters() {

    activeFilters.innerHTML = "";


    selectedCategories.forEach(
        category => {

            const chip =
                document.createElement("div");

            chip.className =
                "active-filter";

            chip.innerHTML = `

                ${escapeHTML(category)}

                <button
                    type="button"
                    data-remove-category="${escapeHTML(category)}"
                >
                    ×
                </button>

            `;

            activeFilters.appendChild(
                chip
            );
        }
    );


    selectedPrices.forEach(
        price => {

            let label =
                price;

            if (price === "under250") {
                label = "Under ₹250";
            }

            if (price === "250to750") {
                label = "₹250 – ₹750";
            }

            if (price === "above750") {
                label = "Above ₹750";
            }


            const chip =
                document.createElement("div");

            chip.className =
                "active-filter";

            chip.innerHTML = `

                ${label}

                <button
                    type="button"
                    data-remove-price="${price}"
                >
                    ×
                </button>

            `;

            activeFilters.appendChild(
                chip
            );
        }
    );


    document
        .querySelectorAll(
            "[data-remove-category]"
        )
        .forEach(button => {

            button.addEventListener(
                "click",
                () => {

                    const value =
                        button.dataset
                            .removeCategory;

                    selectedCategories =
                        selectedCategories.filter(
                            item =>
                                item !== value
                        );

                    document
                        .querySelectorAll(
                            ".category-filter"
                        )
                        .forEach(input => {

                            input.checked =
                                selectedCategories
                                    .includes(
                                        input.value
                                    );

                        });

                    applyFilters();
                }
            );
        });


    document
        .querySelectorAll(
            "[data-remove-price]"
        )
        .forEach(button => {

            button.addEventListener(
                "click",
                () => {

                    const value =
                        button.dataset
                            .removePrice;

                    selectedPrices =
                        selectedPrices.filter(
                            item =>
                                item !== value
                        );

                    document
                        .querySelectorAll(
                            ".price-filter"
                        )
                        .forEach(input => {

                            input.checked =
                                selectedPrices
                                    .includes(
                                        input.value
                                    );

                        });

                    applyFilters();
                }
            );
        });
}


