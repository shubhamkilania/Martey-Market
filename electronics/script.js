function getDiscount(product) {

    if (!product.mrp || product.mrp <= product.price) {
        return 0;
    }

    return Math.round(
        ((product.mrp - product.price) / product.mrp) * 100
    );
}


function escapeHTML(value) {

    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}


function getCart() {

    try {

        const stored =
            localStorage.getItem("marteyCart");

        if (!stored) {
            return [];
        }

        const cart =
            JSON.parse(stored);

        return Array.isArray(cart)
            ? cart
            : [];

    } catch (error) {

        return [];

    }
}


function saveCart(cart) {

    localStorage.setItem(
        "marteyCart",
        JSON.stringify(cart)
    );
}


function getCartQuantity(productId) {

    const cart = getCart();

    const item = cart.find(product =>
        Number(
            product.id ??
            product.productId ??
            product.productID
        ) === Number(productId)
    );

    if (!item) {
        return 0;
    }

    return Number(
        item.quantity ??
        item.qty ??
        1
    );
}


/* =========================================================
   CART COUNT
========================================================= */

function updateCartCount() {

    const cart = getCart();

    const totalQuantity =
        cart.reduce((total, item) => {

            return total +
                Number(
                    item.quantity ??
                    item.qty ??
                    1
                );

        }, 0);

    cartCount.textContent =
        totalQuantity;
}


/* =========================================================
   ADD TO CART
========================================================= */

function addToCart(productId) {

    const product =
        products.find(
            item =>
                Number(item.id) ===
                Number(productId)
        );

    if (!product) {
        return;
    }

    const cart = getCart();

    const existingIndex =
        cart.findIndex(item =>
            Number(
                item.id ??
                item.productId ??
                item.productID
            ) === Number(productId)
        );

    if (existingIndex !== -1) {

        cart[existingIndex].quantity =
            Number(
                cart[existingIndex].quantity ??
                cart[existingIndex].qty ??
                1
            ) + 1;

    } else {

        cart.push({
            id: product.id,
            quantity: 1
        });

    }

    saveCart(cart);

    updateCartCount();
    updateAddButtons();

    const button =
        document.querySelector(
            `.add-button[data-id="${productId}"]`
        );

    if (button) {

        const originalText =
            button.textContent;

        button.textContent =
            "Added ✓";

        button.classList.add("added");

        setTimeout(() => {

            button.textContent =
                originalText;

            button.classList.remove("added");

        }, 900);
    }
}


